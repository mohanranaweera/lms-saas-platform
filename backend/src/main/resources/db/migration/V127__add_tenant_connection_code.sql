-- INST-QR-01: public institute connection code (docs/api/institute-connection.md).
--
-- A short, random, public identifier encoded in the Institute QR
-- ({base-url}/connect/v1/{code}). It is not a secret and grants nothing:
-- scanning it only selects an institute; sign-in is still required.
--
-- * Independent of name, subdomain and custom domains, so renaming the
--   institute or changing its addresses never changes its QR.
-- * Immutable once assigned (trigger below).
-- * Never reissued: if a tenant row is ever deleted, its code moves to
--   retired_institute_connection_code and can't be assigned again.
-- * Generated by the database (48 random bits as 12 lowercase hex chars), so
--   every insert path - registration, fixtures, SQL seeds - gets one.

ALTER TABLE tenant ADD COLUMN connection_code VARCHAR(12);

UPDATE tenant
SET connection_code = substr(replace(gen_random_uuid()::text, '-', ''), 1, 12)
WHERE connection_code IS NULL;

ALTER TABLE tenant
    ALTER COLUMN connection_code SET DEFAULT substr(replace(gen_random_uuid()::text, '-', ''), 1, 12),
    ALTER COLUMN connection_code SET NOT NULL,
    ADD CONSTRAINT uq_tenant_connection_code UNIQUE (connection_code),
    ADD CONSTRAINT chk_tenant_connection_code_format CHECK (connection_code ~ '^[a-z0-9]{12}$');

-- Platform-level registry, not tenant-owned data: its rows outlive the
-- tenant they belonged to, so former_tenant_id deliberately has no FK.
CREATE TABLE retired_institute_connection_code (
    connection_code  VARCHAR(12) PRIMARY KEY,
    former_tenant_id UUID        NOT NULL,
    retired_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE FUNCTION tenant_connection_code_guard() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF TG_OP = 'UPDATE' THEN
        IF NEW.connection_code IS DISTINCT FROM OLD.connection_code THEN
            RAISE EXCEPTION 'tenant.connection_code is immutable';
        END IF;
        RETURN NEW;
    ELSIF TG_OP = 'INSERT' THEN
        IF EXISTS (SELECT 1 FROM retired_institute_connection_code r
                   WHERE r.connection_code = NEW.connection_code) THEN
            RAISE EXCEPTION 'tenant.connection_code % was retired and cannot be reassigned', NEW.connection_code;
        END IF;
        RETURN NEW;
    ELSE -- DELETE
        INSERT INTO retired_institute_connection_code (connection_code, former_tenant_id)
        VALUES (OLD.connection_code, OLD.id)
        ON CONFLICT (connection_code) DO NOTHING;
        RETURN OLD;
    END IF;
END;
$$;

CREATE TRIGGER trg_tenant_connection_code_immutable
    BEFORE UPDATE OF connection_code ON tenant
    FOR EACH ROW EXECUTE FUNCTION tenant_connection_code_guard();

CREATE TRIGGER trg_tenant_connection_code_not_retired
    BEFORE INSERT ON tenant
    FOR EACH ROW EXECUTE FUNCTION tenant_connection_code_guard();

CREATE TRIGGER trg_tenant_connection_code_retire
    AFTER DELETE ON tenant
    FOR EACH ROW EXECUTE FUNCTION tenant_connection_code_guard();
