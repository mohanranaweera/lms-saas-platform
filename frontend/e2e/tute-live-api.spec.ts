const lines: string[] = [];
const results: { area: string; status: "PASS" | "FAIL" | "BLOCKED" | "INFO"; check: string; detail?: string }[] = [];

function section(title: string) {
  lines.push("", `## ${title}`, "");
}
function note(text: string) {
  lines.push(`  - ${text}`);
}
function redact(text: string): string {
  return text
    .replace(/"(accessToken|token|password|newPassword|currentPassword|temporaryPassword|quoteToken)":"[^"]*"/g, '"$1":"<redacted>"')
    .replace(/"bankDetails":\{[^}]*\}/g, '"bankDetails":"<redacted>"')
    .replace(/#token=[A-Za-z0-9._~-]+/g, "#token=<redacted>");
}
function check(area: string, ok: boolean, check: string, detail?: unknown) {
  const d = detail === undefined ? "" : typeof detail === "string" ? detail : JSON.stringify(detail);
  const status = ok ? "PASS" : "FAIL";
  results.push({ area, status, check, detail: d ? redact(d).slice(0, 400) : undefined });
  lines.push(`- **${status}** [${area}] ${check}${d ? ` — ${redact(d).slice(0, 300)}` : ""}`);
  return ok;
}
function blocked(area: string, checkText: string, reason: string) {
  results.push({ area, status: "BLOCKED", check: checkText, detail: reason });
  lines.push(`- **BLOCKED** [${area}] ${checkText} — ${reason}`);
}
function flush() {
  fs.mkdirSync(EVIDENCE, { recursive: true });
  const header = [
    `# TUTE-01 live API evidence (run ${TAG}, ${new Date().toISOString()})`,
    "",
    "Local stack only (demo.lms.test / academy.lms.test :3000 -> backend :8080, DB lms_dev).",
    "Tokens, passwords, invite tokens, quote tokens and tenant bank details are redacted. Bodies truncated to 300 chars.",
    "Generated by `frontend/e2e/tute-live-api.spec.ts`.",
  ];
  fs.writeFileSync(path.join(EVIDENCE, "api-evidence.md"), [...header, ...lines, ""].join("\n"));
  fs.writeFileSync(path.join(EVIDENCE, "results.json"), JSON.stringify({ tag: TAG, results }, null, 2));
}

