    section("Teardown — restore permission matrix");
    const current = await matrix();
    const changes = [...matrixTouched]
      .map((k) => k.split("|"))
      .filter(([role, cap]) => current.tute[cap]?.[role] !== matrixBaseline[cap]?.[role])
      .map(([roleCode, capabilityKey]) => ({ roleCode, capabilityKey, granted: matrixBaseline[capabilityKey][roleCode] === "GRANTED" }));
    if (changes.length) {
      const r = await call(admin, "PUT", "/staff/permission-matrix", { expectedVersion: current.version, changes });
      check("A7", r.status === 200, `restore ${changes.length} touched Tute cells to baseline`, r.status);
    }
    const after = await matrix();
    check("A7", JSON.stringify(after.tute) === JSON.stringify(matrixBaseline), "Tute matrix equals recorded baseline after the run", `version ${after.version}`);
