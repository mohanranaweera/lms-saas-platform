async function matrix(): Promise<{ version: number; tute: Record<string, Record<string, string>> }> {
  const r = await call(admin, "GET", "/staff/permission-matrix", undefined, true);
  const group = r.body.data.groups.find((g: any) => g.key === "TUTE");
  const tute: Record<string, Record<string, string>> = {};
  for (const row of group.rows) tute[row.key] = Object.fromEntries(Object.entries(row.cells).map(([role, cell]: any) => [role, cell.state]));
  return { version: r.body.data.version, tute };
}

async function setGrants(changes: { roleCode: string; capabilityKey: string; granted: boolean }[]): Promise<number> {
  const { version } = await matrix();
  changes.forEach((c) => matrixTouched.add(`${c.roleCode}|${c.capabilityKey}`));
  const r = await call(admin, "PUT", "/staff/permission-matrix", { expectedVersion: version, changes });
  return r.status;
}

