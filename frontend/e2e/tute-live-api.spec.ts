interface Actor {
  label: string;
  base: string;
  token: string;
  email: string;
}
interface Res<T = any> {
  status: number;
  body: { success?: boolean; data?: T; error?: { code?: string; message?: string; fieldErrors?: { field: string }[]; details?: any } | null };
  headers: Record<string, string>;
  raw?: Buffer;
}

let ctx: APIRequestContext;

async function call<T = any>(actor: Actor, method: string, p: string, data?: unknown, quiet = false): Promise<Res<T>> {
  const response = await ctx.fetch(`${actor.base}/api/v1${p}`, {
    method,
    headers: { Authorization: `Bearer ${actor.token}` },
    data: data as any,
  });
  const headers = response.headers();
  const isPdf = (headers["content-type"] ?? "").includes("pdf");
  const raw = await response.body();
  let body: any = {};
  if (!isPdf && raw.length) {
    try {
      body = JSON.parse(raw.toString("utf-8"));
    } catch {
      body = { text: raw.toString("utf-8").slice(0, 200) };
    }
  }
  if (!quiet) {
    const shown = isPdf ? `<pdf ${raw.length} bytes, X-Label-Count=${headers["x-label-count"]}>` : redact(JSON.stringify(body)).slice(0, 300);
    const sent = data === undefined ? "" : ` body=${redact(JSON.stringify(data)).slice(0, 160)}`;
    lines.push(`  - \`${method} ${p}\` (${actor.label})${sent} → **${response.status()}** \`${shown}\``);
  }
  return { status: response.status(), body, headers, raw: isPdf ? raw : undefined };
}

async function login(base: string, email: string, password = PASSWORD, label = email): Promise<Actor> {
  const response = await ctx.post(`${base}/api/v1/auth/login`, { data: { email, password } });
  const body = await response.json().catch(() => ({}));
  lines.push(`  - \`POST /auth/login\` (${label}) → **${response.status()}** \`${redact(JSON.stringify(body)).slice(0, 120)}\``);
  expect(response.status(), `login ${email}`).toBe(200);
  return { label, base, token: body.data.accessToken, email };
}

/** Login with a temporary password and change it to the fixture password (mandatory first change). */
async function loginAndChangePassword(base: string, email: string, label: string): Promise<Actor> {
  const temp = await login(base, email, TEMP_PASSWORD, label);
  const changed = await call(temp, "POST", "/auth/password", { currentPassword: TEMP_PASSWORD, newPassword: PASSWORD });
  expect(changed.status, "password change").toBe(200);
  return { ...temp, token: changed.body.data.accessToken };
}

function err(r: Res) {
  return r.body.error?.code;
}
function fields(r: Res) {
  return (r.body.error?.fieldErrors ?? []).map((f) => f.field);
}
function colomboToday(offsetDays = 0): string {
  const d = new Date(Date.now() + offsetDays * 86_400_000);
  return new Intl.DateTimeFormat("en-CA", { timeZone: "Asia/Colombo", year: "numeric", month: "2-digit", day: "2-digit" }).format(d);
}
function uniquePdf(seed: string): Buffer {
  return Buffer.from(`%PDF-1.4\n%TUTE-01 QA synthetic slip ${seed} ${randomUUID()}\n%%EOF`, "ascii");
}

function psql(sql: string): string | null {
  if (!process.env.PGPASSWORD) return null;
  try {
    return execFileSync(
      "psql",
      ["-h", process.env.PGHOST ?? "localhost", "-p", process.env.PGPORT ?? "5433", "-U", process.env.PGUSER ?? "lms_app", "-d", process.env.PGDATABASE ?? "lms_dev", "-At", "-c", sql],
      { encoding: "utf-8" }
    ).trim();
  } catch (e) {
    return `ERR ${(e as Error).message.slice(0, 200)}`;
  }
}

function pdfText(file: string): string | null {
  try {
    return execFileSync(PDFTOTEXT, ["-enc", "UTF-8", "-layout", file, "-"], { encoding: "utf-8" });
  } catch {
    return null;
  }
}

async function mailpitInviteToken(email: string): Promise<string | null> {
  // The invite is delivered by the notification outbox scheduler, so it can take a while.
  for (let attempt = 0; attempt < 60; attempt++) {
    const search = await ctx.get(`${MAILPIT}/api/v1/search?query=${encodeURIComponent(`to:"${email}"`)}`);
    const list = await search.json().catch(() => ({ messages: [] }));
    const id = list.messages?.[0]?.ID;
    if (id) {
      const message = await (await ctx.get(`${MAILPIT}/api/v1/message/${id}`)).json();
      const match = `${message.Text ?? ""} ${message.HTML ?? ""}`.match(/#token=([^\s"<&]+)/);
      if (match) return match[1];
    }
    await new Promise((r) => setTimeout(r, 1500));
  }
  return null;
}

